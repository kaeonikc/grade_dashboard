"""
zsh Tab completion for `grader` (SPEC.md Part A). Standard library only: the generated `_grader` runs this file
with python3 for its dynamic lists, so Tab never loads grader.py (pandas).

  python3 src/complete.py courses            course folders (with course_info/) under ./ and ./courses/
  python3 src/complete.py undo-ids [COURSE]  id<TAB>description of the undoable history entries, newest first (20)

grader.py uses zsh_script(parser) for `grader completion zsh`, install() for `grader completion install`, and
refresh_installed(parser) on every other run to keep an installed `_grader` in step with the parser.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.history import HISTORY, LOG, undoable  # noqa: E402

HERE = Path(__file__).resolve()
GRADER = HERE.parent.parent / "grader.py"
UNDO_IDS_SHOWN = 20
SUMMARY_WIDTH = 70
MARK = "# generated by `grader completion zsh` from "

# What a value completes to, by (subcommand, dest). Anything not listed that takes a value gets _files.
XLS = "files:*.xls *.xlsx *.csv"
YAML = "files:*.yaml"
VALUES = {
    ("init", "input"): XLS,
    ("init", "abbr"): "text",
    ("init", "course_name"): "text",
    ("init", "term"): "text",
    ("init", "course_id"): "text",
    ("mkdb", "config_file"): YAML,
    ("mkdb", "input"): YAML,
    ("update", "input"): XLS,
    ("update", "config_file"): YAML,
    ("undo", "entry"): "undo-id",
    ("undo", "course"): "course",
    ("sync", "course"): "course",
    ("history", "course"): "course",
    ("history", "n"): "text",
    ("web-push", "course"): "course",
    ("web-push", "semester"): "text",
    ("web-push", "drive_root"): "dir",
    ("web-pull", "course"): "course",
    ("web-pull", "semester"): "text",
    ("web-pull", "drive_root"): "dir",
}

# Modes of one subcommand: once something from one group is on the line, Tab stops offering the other groups.
# Members are dests (options and positionals alike).
EXCLUSIVE = {
    "init": [["input"], ["course_name", "term", "course_id"]],
    "update": [["input"], ["config_file", "purge_empty_orphans", "yes"]],
}


# ---- dynamic lists ------------------------------------------------------------------------------------------
def course_dirs() -> list[Path]:
    """Course folders under ./ and ./courses/, as relative paths (grader's _course_dirs_here)."""
    out = []
    for sp in (Path("."), Path("courses")):
        if sp.is_dir():
            out.extend(sorted(d for d in sp.iterdir() if d.is_dir() and (d / "course_info").is_dir()))
    return out


def resolve_course(course: str | None = None) -> Path | None:
    """COURSE, else the course we're in, else the one here whose history changed last (grader's rule minus .bak)."""
    if course:
        d = Path(course).expanduser()
        return d if (d / "course_info").is_dir() else None
    if Path("course_info").is_dir():
        return Path(".")
    logs = [(log.stat().st_mtime, d) for d in course_dirs() if (log := d / HISTORY / LOG).exists()]
    return max(logs)[1] if logs else None


def _prefix(course: Path) -> str:
    info = course / "course_info"
    cfgs = sorted(f.name for f in info.glob("*_config.yaml")) if info.is_dir() else []
    return cfgs[0][: -len("_config.yaml")] if cfgs else ""


def undo_ids(course: str | None = None) -> list[str]:
    d = resolve_course(course)
    if d is None:
        return []
    prefix = _prefix(d)
    out = []
    for e in undoable(d)[:UNDO_IDS_SHOWN]:
        cells = f", {e['cells']} cells" if e.get("cells") is not None else ""
        files = [Path(f).name.removeprefix(f"{prefix}_") if prefix else Path(f).name for f in e.get("files", [])]
        out.append(f"{e['id']}\t" + _cut(f"[{e.get('tool')} {e.get('action')}{cells}] {', '.join(files)}"))
    return out


# ---- the zsh script -----------------------------------------------------------------------------------------
def _cut(text: str, width: int = SUMMARY_WIDTH) -> str:
    return text if len(text) <= width else text[: width - 1].rstrip() + "…"


def _summary(text: str | None) -> str:
    """Help text up to the first ': ' or '. ' outside parentheses (not 'e.g. '), cut at 70 characters."""
    text = " ".join((text or "").split())
    depth = 0
    for i, ch in enumerate(text):
        depth += (ch == "(") - (ch == ")")
        if depth == 0 and text[i:i + 2] in (": ", ". ") and not text[:i + 1].endswith(("e.g.", "i.e.")):
            text = text[:i]
            break
    return _cut(text)


def _q(text: str) -> str:
    """Escape for inside '…[help]…' of an _arguments spec (single-quoted in the script)."""
    return (text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace(":", "\\:")
            .replace("'", "'\\''"))


def _sq(text: str) -> str:
    """Escape for a single-quoted 'name:description' entry of _describe."""
    return text.replace("'", "'\\''")


def _subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            return dict(a.choices)
    return {}


def _help_of(parser: argparse.ArgumentParser, name: str) -> str:
    for a in parser._actions:
        if isinstance(a, argparse._SubParsersAction):
            for c in a._choices_actions:
                if c.dest == name:
                    return c.help or ""
    return ""


def _fname(cmd: str) -> str:
    return cmd.replace("-", "_")


def _files_action(kind: str) -> str:
    exts = [g.split(".", 1)[1] for g in kind.split(":", 1)[1].split()]
    pat = f"(#i)*.{exts[0]}" if len(exts) == 1 else f"(#i)*.({'|'.join(exts)})"
    return f'_files -g "{pat}(-.)"'


def _value_action(cmd: str, a: argparse.Action) -> str:
    if a.choices and not isinstance(a, argparse._SubParsersAction):
        return "(" + " ".join(map(str, a.choices)) + ")"
    kind = VALUES.get((cmd, a.dest), "")
    if kind.startswith("files:"):
        return _files_action(kind)
    return {"course": "_grader_course", "undo-id": "_grader_undo_ids", "dir": "_files -/", "text": " "}.get(
        kind, "_files")


def _actions(sp: argparse.ArgumentParser) -> tuple[list[argparse.Action], list[argparse.Action]]:
    opts = [a for a in sp._actions if a.option_strings and not isinstance(a, argparse._HelpAction)]
    pos = [a for a in sp._actions if not a.option_strings]
    return opts, pos


def _excluded_by(cmd: str, sp: argparse.ArgumentParser, a: argparse.Action) -> list[str]:
    """What `a` hides: its own option strings, and every member of the other mode groups (positionals by number)."""
    opts, pos = _actions(sp)
    numbers = {p.dest: str(i) for i, p in enumerate(pos, 1)}
    by_dest = {o.dest: list(o.option_strings) for o in opts}
    out = list(a.option_strings)
    for group in EXCLUSIVE.get(cmd, []):
        if a.dest in group:
            for other in EXCLUSIVE[cmd]:
                if other is not group:
                    for dest in other:
                        out.extend(by_dest.get(dest) or [numbers[dest]])
    return out


def _takes_value(a: argparse.Action) -> bool:
    return a.nargs != 0


def _opt_spec(cmd: str, sp: argparse.ArgumentParser, a: argparse.Action) -> str:
    excl = "(" + " ".join(_excluded_by(cmd, sp, a)) + ")"
    names = a.option_strings[0] if len(a.option_strings) == 1 else "{" + ",".join(a.option_strings) + "}"
    value = ""
    if _takes_value(a):
        label = (a.metavar or a.dest).lower().replace("_", " ").replace(":", " ")
        value = f":{label}:{_value_action(cmd, a)}"
    return f"'{excl}'{names}'[{_q(_summary(a.help))}]{value}'"


def _pos_spec(cmd: str, sp: argparse.ArgumentParser, i: int, a: argparse.Action) -> str:
    excl = [x for x in _excluded_by(cmd, sp, a)]
    lead = f"({' '.join(excl)})" if excl else ""
    optional = ":" if a.nargs in ("?", "*") else ""
    msg = (a.metavar or a.dest).lower().replace("_", " ").replace(":", " ")
    return f"'{lead}{i}:{optional}{msg}:_grader_{_fname(cmd)}_arg{i}'"


def _options_helper(cmd: str, sp: argparse.ArgumentParser) -> str:
    """_grader_<cmd>_opts: the options not on the line yet (nor hidden by a mode), for a bare Tab."""
    opts, _ = _actions(sp)
    lines = []
    for a in opts:
        hide = " || ".join(f"${{words[(I){w}]}}" if not w.isdigit() else "0" for w in _excluded_by(cmd, sp, a))
        entries = " ".join(f"'{_sq(s)}:{_sq(_summary(a.help))}'" for s in a.option_strings)
        lines.append(f"  (( {hide} )) || o+=({entries})")
    lines.append("  o+=('-h:show this help message and exit' '--help:show this help message and exit')")
    return (f"_grader_{_fname(cmd)}_opts() {{\n  local -a o\n" + "\n".join(lines) +
            "\n  _describe -t flags 'option' o\n}")


def _command(cmd: str, sp: argparse.ArgumentParser) -> str:
    opts, pos = _actions(sp)
    specs = [_opt_spec(cmd, sp, a) for a in opts] + ["'(- *)'{-h,--help}'[show this help message and exit]'"]
    helpers = []
    for i, a in enumerate(pos, 1):
        specs.append(_pos_spec(cmd, sp, i, a))
        kind = VALUES.get((cmd, a.dest), "")
        tag, desc = ("entries", "history entry") if kind == "undo-id" else ("values", (a.metavar or a.dest).lower()
                                                                             .replace("_", " "))
        values = f"'{tag}:{desc}:{_sq(_value_action(cmd, a))}'"
        helpers.append(f"_grader_{_fname(cmd)}_arg{i}() {{\n"
                       f"  if [[ -z $PREFIX ]]; then\n"
                       f"    _alternative {values} 'flags:option:_grader_{_fname(cmd)}_opts'\n"
                       f"  else\n    _alternative {values}\n  fi\n}}")
    if pos:
        helpers.insert(0, _options_helper(cmd, sp))
    body = " \\\n    ".join(specs)
    return "\n".join(helpers + [f"_grader_cmd_{_fname(cmd)}() {{\n  _arguments -s -S \\\n    {body}\n}}"])


def zsh_script(parser: argparse.ArgumentParser) -> str:
    subs = _subcommands(parser)
    cmd_lines = "\n".join(f"    '{_sq(name)}:{_sq(_summary(_help_of(parser, name)))}'" for name in sorted(subs))
    commands = "\n\n".join(_command(name, sp) for name, sp in sorted(subs.items()))
    return f"""#compdef grader
{MARK}{GRADER}; do not edit
# Rewritten by grader itself when grader.py or src/complete.py changes (SPEC.md Part A).

_grader_py() {{ python3 {_shell_quote(str(HERE))} "$@" 2>/dev/null }}

_grader_course() {{
  local -a c
  c=(${{(f)"$(_grader_py courses)"}})
  (( $#c )) && _wanted courses expl 'course folder' compadd -a c && return 0
  _files -/
}}

# compadd -d, not _describe: _describe folds entries with the same description onto one line, losing the order.
_grader_undo_ids() {{
  local -a lines ids disp
  local i
  local -i w=0
  lines=(${{(f)"$(_grader_py undo-ids ${{~opt_args[--course]}})"}})
  (( $#lines )) || return 1
  ids=(${{lines%%$'\\t'*}})
  for i in $ids; do (( $#i > w )) && w=$#i; done
  for i in $lines; do disp+=("${{(r:w:)${{i%%$'\\t'*}}}}  -- ${{i#*$'\\t'}}"); done
  _wanted -V entries expl 'history entry' compadd -l -d disp -a ids
}}

_grader_commands() {{
  local -a cmds
  cmds=(
{cmd_lines}
  )
  _describe -t commands 'grader command' cmds
}}

# A bare Tab lists the options too. Their tag is `flags`, not `options`: zsh's default tag-order would hold
# `options` back until the other groups came up empty.
_grader_top_opts() {{
  local -a o
  o=('-h:show this help message and exit' '--help:show this help message and exit')
  _describe -t flags 'option' o
}}

_grader_cmd1() {{
  if [[ -z $PREFIX ]]; then
    _alternative 'commands:grader command:_grader_commands' 'flags:option:_grader_top_opts'
  else
    _grader_commands
  fi
}}

{commands}

_grader() {{
  local curcontext="$curcontext" state line ret=1
  typeset -A opt_args
  _arguments -C \\
    '(- *)'{{-h,--help}}'[show this help message and exit]' \\
    '1:grader command:_grader_cmd1' \\
    '*::arg:->args' && ret=0
  if [[ $state == args ]]; then
    curcontext="${{curcontext%:*:*}}:grader-$line[1]:"
    local fn=_grader_cmd_${{line[1]//-/_}}
    if (( $+functions[$fn] )); then $fn && ret=0; else _files && ret=0; fi
  fi
  return ret
}}

_grader "$@"
"""


def _shell_quote(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


# ---- install and self-refresh -------------------------------------------------------------------------------
def target_dir() -> tuple[Path, bool]:
    """(folder for _grader, whether it is surely on zsh's fpath)."""
    if os.environ.get("GRADER_ZSH_COMPLETIONS"):
        return Path(os.environ["GRADER_ZSH_COMPLETIONS"]).expanduser(), True
    home = Path.home()
    if (home / ".oh-my-zsh").is_dir():
        cache = os.environ.get("ZSH_CACHE_DIR") or str(home / ".oh-my-zsh" / "cache")
        return Path(cache) / "completions", True
    return home / ".zsh" / "completions", False


def _ours(path: Path) -> bool:
    """A _grader that this grader.py generated (the header names its path)."""
    try:
        with path.open(encoding="utf-8") as f:
            f.readline()
            return f.readline().rstrip("\n") == f"{MARK}{GRADER}; do not edit"
    except OSError:
        return False


def _write(path: Path, text: str) -> None:
    tmp = path.with_name(f".{path.name}.tmp{os.getpid()}")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def install(parser: argparse.ArgumentParser) -> int:
    folder, on_fpath = target_dir()
    path = folder / "_grader"
    shown = str(path).replace(str(Path.home()), "~", 1)
    if path.exists() and not _ours(path):
        print(f"❌ {shown} exists and wasn't generated by this grader; leaving it alone.")
        return 1
    folder.mkdir(parents=True, exist_ok=True)
    _write(path, zsh_script(parser))
    print(f"✅ wrote {shown} — open a new terminal (or: exec zsh) to use it")
    if not on_fpath:
        print(f"   add this to ~/.zshrc before compinit: fpath=({str(folder).replace(str(Path.home()), '~', 1)} $fpath)")
    return 0


def refresh_installed(parser: argparse.ArgumentParser) -> None:
    """Regenerate an installed _grader when grader.py or this file is newer. Never raises, never prints."""
    try:
        path = target_dir()[0] / "_grader"
        if not path.exists():
            return
        stamp = path.stat().st_mtime
        if max(GRADER.stat().st_mtime, HERE.stat().st_mtime) <= stamp or not _ours(path):
            return
        text = zsh_script(parser)
        if path.read_text(encoding="utf-8") == text:
            os.utime(path)
        else:
            _write(path, text)
    except Exception:
        pass


def main(argv: list[str]) -> int:
    what, arg = (argv[0] if argv else ""), (argv[1] if len(argv) > 1 and argv[1] else None)
    if what == "courses":
        lines = [str(d) for d in course_dirs()]
    elif what == "undo-ids":
        lines = undo_ids(arg)
    else:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    if lines:
        print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
